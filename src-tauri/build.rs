use std::{fs, path::Path};

fn main() {
    // Tauri's generated context expects this file even when bundling is disabled.
    // Keep an existing project icon intact; create a tiny transparent placeholder
    // only when the icon is missing.
    let icon_dir = Path::new("icons");
    let icon_path = icon_dir.join("icon.png");

    if !icon_path.exists() {
        fs::create_dir_all(icon_dir).expect("failed to create Tauri icons directory");
        const PLACEHOLDER_PNG: &[u8] = &[
            0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a, 0x00, 0x00, 0x00, 0x0d, 0x49, 0x48,
            0x44, 0x52, 0x00, 0x00, 0x00, 0x01, 0x00, 0x00, 0x00, 0x01, 0x08, 0x04, 0x00, 0x00,
            0x00, 0xb5, 0x1c, 0x0c, 0x02, 0x00, 0x00, 0x00, 0x0b, 0x49, 0x44, 0x41, 0x54, 0x78,
            0xda, 0x63, 0xfc, 0xff, 0x1f, 0x00, 0x03, 0x03, 0x02, 0x00, 0xef, 0xbf, 0x97, 0x1a,
            0x00, 0x00, 0x00, 0x00, 0x49, 0x45, 0x4e, 0x44, 0xae, 0x42, 0x60, 0x82,
        ];
        fs::write(&icon_path, PLACEHOLDER_PNG).expect("failed to create placeholder Tauri icon");
    }

    tauri_build::build()
}
